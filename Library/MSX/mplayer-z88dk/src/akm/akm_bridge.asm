; akm_bridge.asm — z88dk port of Arkos 2 AKM player.
;
; Strategy:
;   1. The AKM player binary `akm.bin` is built by rasm at ORG = $A000
;      (see Library/MSX/mplayer-z88dk/Makefile).  This bakes absolute
;      jump targets into the binary.
;   2. We INCBIN it here as a blob inside `code_user`, and expose the
;      blob start/end via PUBLIC labels.
;   3. The application calls `mplayer_engine_load()` ONCE at startup,
;      which LDIR-copies the blob from wherever z88dk placed it to
;      $A000 (RAM in MSX page 2 — works for both 16 KiB ROM cart
;      and MSX-DOS .COM, since page 2 is RAM in both layouts).
;   4. Entry-point symbols (`_PLY_AKM_INIT`, `_PLY_AKM_PLAY`, …) are
;      defined in build/akm_bindings.asm — auto-generated per build by
;      compile.sh from rasm's symbol table — because the addresses
;      depend on the AKM build configuration (e.g. PLY_AKM_Rom).
;      Hardcoding them here previously caused silent / single-beep
;      breakage when the player layout shifted.

    SECTION code_user

    ; AKM_BASE: must match the ORG passed to rasm when assembling akm.bin.
    ; $C200 = page 3 RAM ($C000-$FFFF), which is RAM in BOTH 16K-cart
    ; ROM mode AND MSX-DOS2 .COM mode. We previously used $A000 (page 2),
    ; but z88dk's MSX cart CRT switches page 2 to the cart slot at
    ; startup (see /opt/z88dk/lib/target/msx/classic/rom.asm), leaving
    ; $A000 unmapped in ROM mode — the LDIR's writes silently dropped
    ; and AKM played nothing. $C200 sits just above z88dk's typical
    ; BSS region ($C000-$C0xx for the ubox examples) and is comfortably
    ; below the stack at the top of RAM, so it is safe in both modes.
    DEFC AKM_BASE = 0xC200

    ; Loader: must be called once before any mplayer_* function.
    PUBLIC _mplayer_engine_load
_mplayer_engine_load:
    ld hl, _akm_blob_start
    ld de, AKM_BASE
    ld bc, _akm_blob_end - _akm_blob_start
    ldir
    ret

    ; The AKM binary blob.  Generated by:
    ;   /opt/z88dk/bin/.. ../bin/rasm akm.z80 -o akm -s -sl -sq
    ; with akm.z80 wrapping PlayerAkm.asm + alienall config + song data.
    ; See Library/MSX/mplayer-z88dk/Makefile.
    PUBLIC _akm_blob_start
    PUBLIC _akm_blob_end
_akm_blob_start:
    BINARY "akm.bin"
_akm_blob_end:
